def write_sheet(wb, title, columns, rows):
    ws = wb.create_sheet(title)
    ws.append(columns)
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in rows:
        ws.append(list(r))
    ws.freeze_panes = "A2"


def main():
    wb = Workbook()
    wb.remove(wb.active)
    write_sheet(wb, "店", SHOP_COLUMNS, [(*s[:12], s[12], DAY, s[13]) for s in SHOPS])
    write_sheet(wb, "駅", STATION_COLUMNS, STATIONS)
    write_sheet(wb, "移動手段", MODE_COLUMNS, MODES)
    OUT.parent.mkdir(exist_ok=True)
    wb.save(OUT)
    print(f"{OUT} を作りました（店 {len(SHOPS)}、駅 {len(STATIONS)}、移動手段 {len(MODES)}）")


if __name__ == "__main__":
    main()
